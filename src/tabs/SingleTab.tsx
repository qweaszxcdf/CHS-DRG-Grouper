  loadCCCodes: () => ({}),
  loadMCCCodes: () => ({}),
  loadCCECodes: () => ({}),
  loadYBDiagNames: () => ({}),
  loadYBProcNames: () => ({}),
  isGrayDiag: () => false,
  isGrayProc: () => false,
  isInvalidDiagnosis: () => false,
