const createGroupingRequestError = (error: unknown) => {
  const message = error instanceof Error ? error.message : String(error);
  return {
    drg: null,
    mdc: null,
    adrg: null,
    code: 'ERR',
    error: 'GROUPING_REQUEST_FAILED',
    description: message,
    matchTrace: [{ event: 'transport' as const, error: true, description: message }],
  };
};
const normalizeInfoLength = (infos: CodeInfo[], targetLength: number) => {
  const next = [...infos];
  if (next.length > targetLength) next.splice(targetLength);
  while (next.length < targetLength) next.push(createEmptyInfo());
  return next;
};
// helper for keydown handlers: ignore events generated by an active IME
// composition session.  Browsers may indicate this with `isComposing` on the
// synthetic or native event or by emitting a `Process` key.  The input logic
// should simply return early when the user is still choosing characters.
function isIMEComposing(e: KeyboardEvent<HTMLInputElement> & { isComposing?: boolean }) {
  if (e.isComposing) return true;
  if (e.nativeEvent.isComposing) return true;
  if (e.key === 'Process') return true;
  return false;
}

